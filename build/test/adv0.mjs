import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'allow' });
const page = await ctx.newPage();
let loads = 0;
page.on('framenavigated', f => { if (f === page.mainFrame()) { loads++; console.log(`   [nav ${loads}] ${f.url()}`); } });
console.log('FIRST EVER VISIT to /#/read/s/paste (fresh profile, no SW yet):');
await page.goto(`${BASE}/#/read/s/paste`, { waitUntil: 'load' });
await page.waitForTimeout(800);
await page.fill('#src', '私が入力した大事なテキスト');
console.log('   typed into #src, waiting 4s…');
await page.waitForTimeout(4000);
const val = await page.locator('#src').inputValue().catch(e => '(gone: '+e.message.slice(0,40)+')');
console.log(`   navigations so far: ${loads}`);
console.log(`   textarea value after wait: ${JSON.stringify(val)}`);
const reg = await page.evaluate(async () => { const r = await navigator.serviceWorker.getRegistration(); return {active:!!r?.active, ctrl:!!navigator.serviceWorker.controller}; });
console.log('   sw:', JSON.stringify(reg));
await browser.close();
