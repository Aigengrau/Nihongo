import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push('pageerror: ' + e.message));

console.log('C2. kana quiz: answer then navigate away');
await page.goto(`${BASE}/#/kana`, { waitUntil: 'load' });
await page.waitForTimeout(2500);
await page.evaluate(() => document.getElementById('quiz').click());
await page.waitForTimeout(500);
console.log('   sheet open:', await page.locator('#sheet').isVisible());
await page.evaluate(() => document.querySelector('#opts [data-r]').click());
await page.evaluate(() => { location.hash = '/today'; });
await page.waitForTimeout(1500);
console.log('   after navigating to Today: appbar="'+await page.locator('#appbarTitle').innerText()+'" sheetVisible='+await page.locator('#sheet').isVisible());
console.log('   body.style.overflow =', JSON.stringify(await page.evaluate(()=>document.body.style.overflow)));
console.log('   sheet content:', (await page.locator('#sheetBody').innerText().catch(()=> '')).slice(0,60).replace(/\s+/g,' '));
console.log('   errors:', errs.length?errs:'none'); errs.length=0;

console.log('\nC3. business keigo drill: answer then navigate away');
await page.goto(`${BASE}/#/business/keigo-irregulars`, { waitUntil: 'load' });
await page.waitForTimeout(1500);
await page.evaluate(() => document.querySelector('[data-m="drill"]').click());
await page.waitForTimeout(600);
console.log('   drill options:', await page.locator('#opts [data-a]').count());
await page.evaluate(() => document.querySelector('#opts [data-a]').click());
await page.evaluate(() => { location.hash = '/stats'; });
await page.waitForTimeout(2500);
console.log('   on Stats: appbar="'+await page.locator('#appbarTitle').innerText()+'"');
console.log('   errors:', errs.length?errs:'none'); errs.length=0;
await browser.close();
