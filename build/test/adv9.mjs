import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push('pageerror: ' + e.message));
await ctx.route('**/data/levels/n3/vocab.json', async r => { await new Promise(res=>setTimeout(res,2500)); await r.continue(); });

console.log('F. from Stats, tap N3 words, then change your mind 300ms later');
await page.goto(`${BASE}/#/stats`, { waitUntil: 'load' });
await page.waitForTimeout(3000);
await page.evaluate(() => { location.hash = '/words/N3'; });
await page.waitForTimeout(300);
await page.evaluate(() => { location.hash = '/saved'; });
await page.waitForTimeout(600);
console.log('   immediately: hash='+await page.evaluate(()=>location.hash)+' appbar="'+await page.locator('#appbarTitle').innerText()+'" body='+(await page.locator('#view').innerText()).slice(0,45).replace(/\s+/g,' '));
await page.waitForTimeout(3500);
console.log('   3.5s later : hash='+await page.evaluate(()=>location.hash)+' appbar="'+await page.locator('#appbarTitle').innerText()+'" body='+(await page.locator('#view').innerText()).slice(0,45).replace(/\s+/g,' '));
console.log('   words-screen search box now on /saved?', await page.locator('#q').count());
console.log('   tabbar:', await page.evaluate(()=>[...document.querySelectorAll('#tabbar [data-tab]')].map(a=>a.dataset.tab+'='+a.getAttribute('aria-current')).join(' ')));
console.log('   errors:', errs.length?errs:'none');
await browser.close();
