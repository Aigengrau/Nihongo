import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
await ctx.route('**/data/levels/n3/vocab.json', async r => { await new Promise(res=>setTimeout(res,2500)); await r.continue(); });
await page.goto(`${BASE}/#/stats`, { waitUntil: 'load' });
await page.waitForTimeout(3000);
await page.evaluate(() => { location.hash = '/words/N3'; });
await page.waitForTimeout(300);
await page.evaluate(() => { location.hash = '/saved'; });
await page.waitForTimeout(4000);
const snap = async t => console.log(`  ${t}: hash=`+await page.evaluate(()=>location.hash)+' appbar="'+await page.locator('#appbarTitle').innerText()+'" #q='+await page.locator('#q').count()+' body='+(await page.locator('#view').innerText()).slice(0,35).replace(/\s+/g,' ')+' tab='+await page.evaluate(()=>[...document.querySelectorAll('#tabbar [data-tab]')].map(a=>a.dataset.tab+'='+a.getAttribute('aria-current')).filter(s=>/page/.test(s)).join(',')));
await snap('clobbered');
console.log('user taps the Saved tab again (already on #/saved):');
await page.locator('#tabbar [data-tab="saved"]').click({ force: true });
await page.waitForTimeout(1500); await snap('after saved tap');
console.log('user presses the appbar back button (hidden?='+await page.evaluate(()=>document.getElementById("backBtn").hidden)+'):');
await page.evaluate(()=>document.getElementById('backBtn').click());
await page.waitForTimeout(2000); await snap('after back');
await browser.close();
