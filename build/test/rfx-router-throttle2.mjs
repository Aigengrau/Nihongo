import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const run = async (lat, kbps, waitOnLevels) => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ ...devices['Pixel 7'], serviceWorkers: 'block' });
  const page = await ctx.newPage();
  const reqs = [];
  page.on('response', r => { if (/vocab\.json/.test(r.url())) reqs.push(r.url().split('/data/')[1]); });
  const cdp = await ctx.newCDPSession(page);
  await cdp.send('Network.enable');
  await cdp.send('Network.emulateNetworkConditions', { offline:false, latency:lat, downloadThroughput:kbps*1024/8, uploadThroughput:kbps*1024/8 });
  await page.goto(`${BASE}/#/levels`, { waitUntil: 'load' });
  await page.waitForSelector('#view .tile, #view a, #view button', { timeout: 60000 }).catch(()=>{});
  await page.waitForTimeout(waitOnLevels);
  await page.evaluate(() => { location.hash = '/words/N1'; });
  await page.waitForTimeout(400);
  await page.evaluate(() => { location.hash = '/saved'; });
  const snap = async (tag) => console.log(`  ${tag}: hash=`+await page.evaluate(()=>location.hash)+' appbar="'+await page.locator('#appbarTitle').innerText()+'" body='+(await page.locator('#view').innerText()).slice(0,40).replace(/\s+/g,' ')+' #q='+await page.locator('#q').count()+' tabs='+await page.evaluate(()=>[...document.querySelectorAll('#tabbar [data-tab]')].map(a=>a.dataset.tab+'='+a.getAttribute('aria-current')).filter(s=>/page/.test(s)).join(',')));
  await page.waitForTimeout(1000); await snap('t+1s');
  await page.waitForTimeout(30000); await snap('t+31s');
  console.log('  vocab fetches:', reqs.join(' '));
  await browser.close();
};
console.log('Slow 4G (300ms, 400kbps), no dwell on levels');
await run(300, 400, 0);
console.log('Regular 3G (400ms, 1600kbps), no dwell');
await run(400, 1600, 0);
