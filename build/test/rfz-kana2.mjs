import { chromium, devices } from 'playwright';
const BASE = 'http://localhost:8099';
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['Pixel 7'] });
const page = await ctx.newPage();
await page.addInitScript(() => {
  window.__spoke = [];
  const orig = window.speechSynthesis && window.speechSynthesis.speak;
  if (window.speechSynthesis) window.speechSynthesis.speak = function (u) { window.__spoke.push(u.text); try { return orig.call(this, u); } catch (e) {} };
});
await page.goto(`${BASE}/#/kana`, { waitUntil: 'load' });
await page.waitForTimeout(2500);
const cell = () => page.locator('.kana-cell[data-id]').first();
await cell().click(); await page.waitForTimeout(400);
console.log('spoken after 1 tap (no switch):', await page.evaluate(() => window.__spoke));
await page.evaluate(() => window.__spoke = []);
await page.click('[data-s="kata"]'); await page.waitForTimeout(600);
await cell().click(); await page.waitForTimeout(600);
console.log('spoken after 1 tap (post-switch):', await page.evaluate(() => window.__spoke));
await browser.close();
